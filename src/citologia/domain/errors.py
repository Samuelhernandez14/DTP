class CitologiaError(Exception):
    """Base de todos los errores controlados del proyecto."""

class ConfigurationError(CitologiaError): ...
class InvalidDocumentError(CitologiaError): ...   # no se reintenta -> cuarentena
class PDFExtractionError(CitologiaError): ...
class OCRError(CitologiaError): ...
class AIProviderError(CitologiaError): ...        # transitorio -> reintentable
class DatabaseError(CitologiaError): ...